--資料庫表格命名方式說明
--第1,2碼=系統類別
--Hm = 人事系統(Human Management)
--In = 勞健保系統(Insurance)
--Lv = 請假系統(Leave)
--Ot = 加班系統(Overtime)
--Tc = 刷卡系統(Timecard)
--Pr = 薪資系統(Payroll)
--Bn = 獎金系統(Bonus)
--Py = 扣繳憑單系統(Pay Year Tax)

--第3碼=檔案屬性類別
--0 = 代碼檔,COD,KEY,SET
--1 = 主檔,MAS,EMP,COM,SAL
--2 = 日計檔,DAY,DAT
--3 = 月計檔,MON
--4 = 年計檔,YER
--5 = 歷史檔,HIS,其他應用檔,View的借用檔
--9 = 暫時檔(會清除掉),TMP

--第4,5,6碼=檔案內容說明 及 第7,8碼=序號
--Emp10 = 員工基本資料檔
--Emp20 = 員工相關資料檔

--如:人事出勤系統,命名範例如下:
--Hm0Dep10 人事系統部門代號檔
--Hm1Emp10 員工基本資料檔
--Hm1Emp20Relative 員工眷屬資料檔
--Hm1Emp20Experience 員工經歷資料檔
--Hm1Emp20SchoolLevel 員工學歷資料檔
--Hm1Emp20Licence 員工證照資料檔
--Lv0Set10 考勤系統假別代號檔
--Lv2Day10 每日請假資料檔
--Lv2Day20 每日助理請假輸入資料檔
--Lv3Mon10 每月請假總檔
--Lv4Yer10 年度請假總檔
